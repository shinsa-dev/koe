#!/usr/bin/env python3
# usage: scripts/tokens.py [--check]: writes Sources/Koe/UI/Tokens.swift from shinsa's packages/ui/src/styles/globals.css.
# Ported from shinsa-ios's scripts/tokens.py: the same OKLCH to sRGB conversion, writing NSColor instead of UIColor.
import math
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.environ.get("SHINSA_REPO", os.path.expanduser("~/Developer/Projects/shinsa"))
OUT = os.path.join(ROOT, "Sources/Koe/UI/Tokens.swift")
SOURCE = "packages/ui/src/styles/globals.css"
SKIP = re.compile(r"shadow|^radius|^font|^text|^tracking|^leading|^selection")


def read_css(ref):
    return subprocess.check_output(["git", "-C", REPO, "show", f"{ref}:{SOURCE}"], text=True)


def blocks(css, selector):
    found = {}
    for match in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        selectors = [s.strip() for s in re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S).split(",")]
        if selector in selectors:
            body = re.sub(r"/\*.*?\*/", "", match.group(2), flags=re.S)
            for name, value in re.findall(r"--([a-z0-9-]+)\s*:\s*([^;]+);", body):
                found[name] = " ".join(value.split())
    return found


def oklch_to_srgb(l, c, h):
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )

    def encode(x):
        x = min(max(x, 0.0), 1.0)
        return 12.92 * x if x <= 0.0031308 else 1.055 * x ** (1 / 2.4) - 0.055

    return tuple(round(encode(x) * 255) for x in linear)


def resolve(name, tokens, depth=0):
    if depth > 20:
        raise ValueError(name)
    return parse(tokens[name], tokens, depth)


def parse(value, tokens, depth):
    value = value.strip()
    if value == "transparent":
        return (0.0, 0.0, 0.0, 0.0)
    var = re.fullmatch(r"var\(--([a-z0-9-]+)\)", value)
    if var:
        return resolve(var.group(1), tokens, depth + 1)
    oklch = re.fullmatch(r"oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*/\s*([\d.]+))?\)", value)
    if oklch:
        l, c, h, alpha = oklch.groups()
        return (float(l), float(c), float(h), float(alpha) if alpha else 1.0)
    mix = re.fullmatch(r"color-mix\(in oklch,\s*(.+?)\s+([\d.]+)%,\s*(.+)\)", value)
    if mix:
        first, share, second = mix.groups()
        p = float(share) / 100
        a, b = parse(first, tokens, depth + 1), parse(second, tokens, depth + 1)
        if b[3] == 0:
            return (a[0], a[1], a[2], a[3] * p)
        return tuple(x * p + y * (1 - p) for x, y in zip(a, b))
    raise ValueError(f"{value!r}")


def hex_of(color):
    l, c, h, alpha = color
    r, g, b = oklch_to_srgb(l, c, h)
    return f"0x{r:02X}{g:02X}{b:02X}{round(alpha * 255):02X}"


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() if not part.isdigit() else part for part in rest)


def render(css, commit):
    light = blocks(css, ":root")
    dark = dict(light)
    dark.update(blocks(css, ".dark"))
    lines = [
        "// swiftlint:disable all",
        "import AppKit",
        "",
        f"// Generated by scripts/tokens.py from shinsa's {SOURCE} at {commit}. Don't edit; run the script.",
        "enum Tokens {",
    ]
    for name in light:
        if SKIP.search(name):
            continue
        try:
            pair = hex_of(resolve(name, light)), hex_of(resolve(name, dark))
        except (ValueError, KeyError):
            continue
        lines.append(f"    static let {camel(name)} = NSColor.token(light: {pair[0]}, dark: {pair[1]})")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    existing = open(OUT).read() if os.path.exists(OUT) else ""
    pinned = re.search(r" at ([0-9a-f]{40})\.", existing)
    check = "--check" in sys.argv
    commit = pinned.group(1) if check and pinned else subprocess.check_output(
        ["git", "-C", REPO, "rev-parse", os.environ.get("SHINSA_REF", "origin/main")], text=True).strip()
    text = render(read_css(commit), commit)
    if check:
        if text != existing:
            sys.exit(f"Tokens.swift doesn't match shinsa {commit}; run scripts/tokens.py")
        print(f"Tokens.swift matches shinsa {commit}")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print(f"Wrote Tokens.swift from shinsa {commit}")


main()
